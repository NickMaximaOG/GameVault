package com.gamevault;

import static org.junit.jupiter.api.Assertions.*;

import org.junit.jupiter.api.Test;

class PasswordHasherTest {
    @Test
    void hashVerifiesAndHasUnderlyingFormat() {
        String h = PasswordHasher.hash("Correct-horse-9");
        assertTrue(h.startsWith("pbkdf2-sha256$600000$"));
        assertEquals(4, h.split("\\$").length);
        assertTrue(PasswordHasher.verify("Correct-horse-9", h));
    }

    @Test
    void wrongPasswordAndGarbageAreRejected() {
        String h = PasswordHasher.hash("Correct-horse-9");
        assertFalse(PasswordHasher.verify("correct-horse-9", h));
        assertFalse(PasswordHasher.verify("x", "not a hash"));
        assertFalse(PasswordHasher.verify("x", "pbkdf2-sha256$notanumber$AA==$AA=="));
        assertFalse(PasswordHasher.verify("x", "md5$1$AA==$AA=="));
    }

    @Test
    void saltsDiffer() {
        assertNotEquals(PasswordHasher.hash("same-password-1"), PasswordHasher.hash("same-password-1"));
    }

    @Test
    void databaseSeedFormatIsCompatible() {
        // Generated by database/tools/gen_schema.py (Python hashlib.pbkdf2_hmac) for the password below.
        String fromPython = "pbkdf2-sha256$1000$AAECAwQFBgcICQoLDA0ODw==$"
                + java.util.Base64.getEncoder().encodeToString(pbkdf2Reference());
        assertTrue(PasswordHasher.verify("ChangeMe!2026", fromPython));
    }

    private static byte[] pbkdf2Reference() {
        try {
            var spec = new javax.crypto.spec.PBEKeySpec("ChangeMe!2026".toCharArray(),
                    java.util.Base64.getDecoder().decode("AAECAwQFBgcICQoLDA0ODw=="), 1000, 256);
            return javax.crypto.SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256").generateSecret(spec).getEncoded();
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }

    @Test
    void rehashDetection() {
        assertFalse(PasswordHasher.needsRehash(PasswordHasher.hash("abc12345678")));
        assertTrue(PasswordHasher.needsRehash("pbkdf2-sha256$1000$AA==$AA=="));
        assertTrue(PasswordHasher.needsRehash("garbage"));
    }

    @Test
    void sha256HexIsStable() {
        assertEquals("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", PasswordHasher.sha256Hex("abc"));
    }
}
